import { Code } from "aws-cdk-lib/aws-lambda";
import { resolve } from "node:path";
import { existsSync, readFileSync } from "node:fs";
import { createProspectusBackend } from "./create-backend";
const evaluation = JSON.parse(readFileSync(resolve("evaluation-deployment.json"), "utf8"));
const artifact = resolve(".artifacts/backend/bootstrap.zip");
if (!existsSync(artifact)) throw new Error("Build the reviewed source-locked Rust Lambda before Amplify deployment");
const intakeArtifact = resolve(".artifacts/intake-evaluation");
if (evaluation.enabled && !existsSync(resolve(intakeArtifact, "prospectus-s3-controls"))) throw new Error("Build the reviewed evaluation runtime before enabling intake");
createProspectusBackend(() => Code.fromAsset(artifact), evaluation.enabled ? () => Code.fromAsset(intakeArtifact) : undefined);
