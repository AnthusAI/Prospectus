import { IdentityFileError } from "../accounts/identity-files";
import { isPlainRecord } from "../accounts/validation-rules";
import { QuotaError } from "./model";
import type { CostLedger } from "./costs";

/**
 * The scheduled usage drain (docs/COST_ACCOUNTING.md, features/cost-usage-queue.feature). Once a minute it reads
 * every product's usage queue and records each message in the cost ledger. The product is the queue's, never the
 * message's. A recorded message is deleted. A message that can never be recorded (malformed, unknown fields, wrong
 * product, unknown item kind, unknown Account) is made visible again at once so it reaches the dead-letter queue
 * after the queue's receive limit. A message that failed for a passing reason (store or table unavailable, busy) is
 * left alone and retried after the visibility timeout. Logs carry reason codes and counts only, never message bodies.
 */

/** The SQS calls the drain needs, so tests run against a fake. */
export interface UsageQueueClient {
  receive(queueUrl: string, maximum: number): Promise<Array<{ body: string; receiptHandle: string }>>;
  delete(queueUrl: string, receiptHandle: string): Promise<void>;
  /** Makes a message visible again immediately. */
  release(queueUrl: string, receiptHandle: string): Promise<void>;
}

export interface DrainOptions {
  client: UsageQueueClient;
  /** Registered product to its queue URL, generated by infrastructure from the product registry. */
  queues: Readonly<Record<string, string>>;
  ledger: Pick<CostLedger, "recordUsage">;
  /** Receive calls per queue per run, ten messages each. */
  maximumBatches?: number;
  /** Stop starting new batches once this returns false (the Lambda's remaining time). */
  hasTime?: () => boolean;
  log?: (entry: Record<string, unknown>) => void;
}

export interface DrainCounts {
  recorded: number;
  refused: number;
  deferred: number;
}

const PASSING = new Set(["quota_unavailable", "busy", "quota_capacity"]);

export function usageQueues(value: unknown): Record<string, string> {
  if (!isPlainRecord(value)) throw new Error("Usage queues must be a product to queue URL map.");
  for (const [product, url] of Object.entries(value))
    if (
      !/^[a-z][a-z0-9-]{0,71}$/.test(product) ||
      typeof url !== "string" ||
      !/^https:\/\/sqs\.[a-z0-9-]+\.amazonaws\.com\/\d{12}\/prospectus-usage-[a-z0-9-]+$/.test(url)
    )
      throw new Error("Each usage queue is a registered product and its Prospectus queue URL.");
  return value as Record<string, string>;
}

export async function drainUsage(options: DrainOptions): Promise<DrainCounts> {
  const counts: DrainCounts = { recorded: 0, refused: 0, deferred: 0 };
  const log = options.log ?? (() => {});
  const hasTime = options.hasTime ?? (() => true);
  for (const [product, queueUrl] of Object.entries(options.queues)) {
    for (let batch = 0; batch < (options.maximumBatches ?? 10) && hasTime(); batch++) {
      let messages: Array<{ body: string; receiptHandle: string }>;
      try {
        messages = await options.client.receive(queueUrl, 10);
      } catch {
        log({ event: "usage.drain.receive_failed", product });
        break;
      }
      if (!messages.length) break;
      for (const message of messages) {
        const outcome = await recordOne(options.ledger, product, message.body);
        try {
          if (outcome.kind === "recorded") {
            await options.client.delete(queueUrl, message.receiptHandle);
            counts.recorded++;
          } else if (outcome.kind === "refused") {
            await options.client.release(queueUrl, message.receiptHandle);
            counts.refused++;
            log({ event: "usage.drain.refused", product, reason: outcome.code });
          } else {
            counts.deferred++;
            log({ event: "usage.drain.deferred", product, reason: outcome.code });
          }
        } catch {
          // Deleting or releasing failed: the message comes back after its visibility timeout and is recorded once.
          log({ event: "usage.drain.acknowledge_failed", product });
        }
      }
      if (messages.length < 10) break;
    }
  }
  log({ event: "usage.drain.done", ...counts });
  return counts;
}

async function recordOne(
  ledger: Pick<CostLedger, "recordUsage">,
  product: string,
  body: string,
): Promise<{ kind: "recorded" } | { kind: "refused" | "deferred"; code: string }> {
  let parsed: unknown;
  try {
    parsed = JSON.parse(body);
  } catch {
    return { kind: "refused", code: "invalid_json" };
  }
  try {
    await ledger.recordUsage(product, parsed);
    return { kind: "recorded" };
  } catch (error) {
    if (error instanceof QuotaError)
      return PASSING.has(error.code) || error.status >= 500
        ? { kind: "deferred", code: error.code }
        : { kind: "refused", code: error.code };
    if (error instanceof IdentityFileError) return { kind: "deferred", code: `storage_${error.code}` };
    return { kind: "deferred", code: "unexpected" };
  }
}

/** The real SQS client. Long polling is off: the drain runs on a schedule and must not wait on empty queues. */
export class SqsUsageQueueClient implements UsageQueueClient {
  constructor(private sqs: import("@aws-sdk/client-sqs").SQSClient) {}
  async receive(queueUrl: string, maximum: number) {
    const { ReceiveMessageCommand } = await import("@aws-sdk/client-sqs");
    const result = await this.sqs.send(
      new ReceiveMessageCommand({ QueueUrl: queueUrl, MaxNumberOfMessages: maximum, WaitTimeSeconds: 0 }),
    );
    return (result.Messages ?? []).flatMap((message) =>
      message.Body !== undefined && message.ReceiptHandle
        ? [{ body: message.Body, receiptHandle: message.ReceiptHandle }]
        : [],
    );
  }
  async delete(queueUrl: string, receiptHandle: string) {
    const { DeleteMessageCommand } = await import("@aws-sdk/client-sqs");
    await this.sqs.send(new DeleteMessageCommand({ QueueUrl: queueUrl, ReceiptHandle: receiptHandle }));
  }
  async release(queueUrl: string, receiptHandle: string) {
    const { ChangeMessageVisibilityCommand } = await import("@aws-sdk/client-sqs");
    await this.sqs.send(
      new ChangeMessageVisibilityCommand({
        QueueUrl: queueUrl,
        ReceiptHandle: receiptHandle,
        VisibilityTimeout: 0,
      }),
    );
  }
}
